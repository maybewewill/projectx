#!/usr/bin/env python3
"""Differential vectors for the training queue slot removal of Game.dll 1.26a (docs/spec/economy-4.md).

Runs the ORIGINAL queue shift `CAbilityTrain::vf208` (0x6F1652A0) in Unicorn on random queues and
records the before/after state of the queue fields:

  count  +0x9C          (dword, number of used slots; NOT changed by the shift)
  slots  +0xA0 + 4*i    (dword, type ids; 7 slots, the 8th is cleared by the shift)
  mask   +0xBC          (dword, one bit per slot, shifted with the slots)

Only removals of a slot with index >= 1 are run: those paths make no calls (the index-0 path
calls the owner and the UI helpers, which need a full game object and are not isolated here).

    GAME_DLL=/path/to/Game.dll PYTHONPATH=<dir with unicorn, pefile> \\
        python3 tools/emu/train_queue_emu.py --seed 1 --n 3000 --rs crates/sim/tests/economy/train_vectors.rs

The generated Rust file holds plain numbers only. Do not hand-edit.
"""
import argparse
import os
import random
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "jasscomp"))
import jcomp  # noqa: E402

SHIFT = 0x6F1652A0    # CAbilityTrain::vf208: thiscall, one stack argument (the slot index)
OFF_COUNT = 0x9C
OFF_SLOTS = 0xA0
OFF_MASK = 0xBC
CAP = 7


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--n", type=int, default=3000)
    ap.add_argument("--rs", default=None)
    args = ap.parse_args()

    H = jcomp.Harness()
    n_init, failed = jcomp.run_crt_init(H)
    print(f"initialisers run: {n_init}, failed: {len(failed)}")

    obj = H.alloc(0x200)
    rng = random.Random(args.seed)
    cases = []
    for _ in range(args.n):
        count = rng.randint(2, CAP)
        index = rng.randint(1, count - 1)
        slots = [rng.randint(1, 0xFFFFFFFF) for _ in range(CAP)]
        mask = rng.getrandbits(32)
        for i in range(0x200 // 4):
            H.wr32(obj + 4 * i, 0)
        H.wr32(obj + OFF_COUNT, count)
        for i in range(CAP):
            H.wr32(obj + OFF_SLOTS + 4 * i, slots[i])
        H.wr32(obj + OFF_MASK, mask)
        H.call(SHIFT, ecx=obj, stack=(index,))
        after_count = H.rd32(obj + OFF_COUNT)
        after_slots = [H.rd32(obj + OFF_SLOTS + 4 * i) for i in range(CAP)]
        after_mask = H.rd32(obj + OFF_MASK)
        # CONFIRMED by the decompile: the shift does not change the count (the caller does).
        assert after_count == count, (count, index, after_count)
        cases.append((count, index, slots, mask, after_count, after_slots, after_mask))

    print(f"shift cases: {len(cases)}")
    if args.rs:
        with open(args.rs, "w") as fh:
            fh.write("// Generated by tools/emu/train_queue_emu.py from the original Game.dll (1.26a) in Unicorn.\n")
            fh.write("// (count, removed index, slots before, mask before, count after, slots after, mask after).\n")
            fh.write("// Do not hand-edit.\n\n")
            fh.write("#![allow(clippy::unreadable_literal, clippy::type_complexity)]\n\n")
            fh.write("/// (count, index, slots, mask, count_after, slots_after, mask_after)\n")
            fh.write("pub const TRAIN_SHIFT_VECTORS: &[(u32, u32, [u32; 7], u32, u32, [u32; 7], u32)] = &[\n")
            for count, index, slots, mask, ac, asl, am in cases:
                sl = ", ".join("0x%08X" % s for s in slots)
                sa = ", ".join("0x%08X" % s for s in asl)
                fh.write("    (%d, %d, [%s], 0x%08X, %d, [%s], 0x%08X),\n" % (count, index, sl, mask, ac, sa, am))
            fh.write("];\n")
        print("wrote", args.rs)


if __name__ == "__main__":
    main()
