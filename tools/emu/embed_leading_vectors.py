"""Writes crates/w3g/tests/leading_vectors.rs from the replay_leading_emu harness (docs/spec/replay-load.md, 3).

Each case is a synthetic body and build number, with the landings of the original's reader (verified
equal to the Python model first). Usage:

    GAME_DLL=/path/Game.dll python3 -I tools/emu/embed_leading_vectors.py <out.rs> [cases] [seed]
"""
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import replay_leading_emu as R  # noqa: E402


def hx(b):
    return "" if b is None else b.hex()


def opt(b):
    return "None" if b is None else f'Some("{hx(b)}")'


def main(argv):
    out = argv[0]
    cases = int(argv[1]) if len(argv) > 1 else 24
    seed = int(argv[2]) if len(argv) > 2 else 5
    rng = random.Random(seed)
    lines = [
        "// Generated by tools/emu/embed_leading_vectors.py from the Unicorn run of Game.dll 1.26a",
        "// (docs/spec/replay-load.md, section 3). Do not edit by hand.",
        "//",
        "// Each case: a synthetic body, its build number, and what the original's reader produced.",
        "// `error: true` = the original stopped with an error (position limit + 1).",
        "",
        "pub struct Case {",
        "    pub build: u32,",
        "    pub body: &'static str,",
        "    pub error: bool,",
        "    pub name_a: &'static str,",
        "    pub name_b: Option<&'static str>,",
        "    pub c32: &'static str,",
        "    pub c16: &'static str,",
        "    pub stat: &'static str,",
        "    pub u32_b0: u32,",
        "    pub u32_b4: u32,",
        "    pub blob: Option<&'static str>,",
        "    pub tail20: Option<&'static str>,",
        "    pub name_tail: Option<&'static str>,",
        "}",
        "",
        "pub const CASES: &[Case] = &[",
    ]
    done = 0
    tries = 0
    while done < cases:
        tries += 1
        build = rng.choice([6059, 6040, 6000, 5999])
        body = R.random_body(rng, build)
        o = R.run_original(body, build)
        m = R.model_read(body, build)
        bad = R.compare(o, m, build)
        if bad:
            raise SystemExit(f"model and original disagree: {bad}")
        if m["error"] and rng.random() < 0.6:
            continue
        blk = m.get("block", {})
        lines += [
            "    Case {",
            f"        build: {build},",
            f'        body: "{body.hex()}",',
            f"        error: {'true' if m['error'] else 'false'},",
            f'        name_a: "{hx(m.get("str_a"))}",',
            (f'        name_b: Some("{hx(m.get("str_b"))}"),' if build >= 0x178B else "        name_b: None,"),
            f'        c32: "{hx(blk.get("c32"))}",',
            f'        c16: "{hx(blk.get("c16"))}",',
            f'        stat: "{hx(blk.get("c128"))}",',
            f'        u32_b0: {blk.get("u32_b0", 0)},',
            f'        u32_b4: {blk.get("u32_b4", 0)},',
            f'        blob: {opt(m.get("blob"))},',
            f'        tail20: {opt(m.get("tail20"))},',
            f'        name_tail: {opt(m.get("str_tail"))},',
            "    },",
        ]
        done += 1
    lines.append("];")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {done} cases ({tries} drawn) to {out}")


if __name__ == "__main__":
    main(sys.argv[1:])
