"""Probe of the missile move-target routine's path request 0x6F496D10 (Game.dll 1.26a), S13 item 3.

0x6F497080 (the unit/missile point-move setup, thiscall on the mover M) calls
    0x6F496D10(vec3, p_a, p_b, M+0x38, M+0x50, &t)       (stdcall, 6 stack arguments)
with vec3 = the move vector in cells (target - start, x y z), p_a = the float pointer 'a3' of 0x6F497080 (the launch
record's Missilespeed rec+0x4C divided by 32, in cells per second), p_b = the pointer 'a6' (the launch record's arc
rec+0x50, held in the property at missile+0x8C). This script runs the real 0x6F496D10 with chosen inputs and prints
the three outputs; with `--rs path` it writes the vector file crates/sim/tests/missile/cap_vectors.rs.

Outputs: O6 = the flight time T = sqrt(dx^2 + dy^2) / A (soft float; zero when A <= 0, the move is zero or T < 0.1),
O5 = the velocity (dx, dy) * recip(T), O4 = the vertical parabola terms (-c/T, c) with c = 4 * arc * A + dz / T.

Usage: GAME_DLL=... py tools/emu/missile_cap_emu.py [--rs out.rs]
"""
import math
import os
import random
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import emu  # noqa: E402

mu = emu.mu
EXTRA = 0x00400000
mu.mem_map(EXTRA, 0x10000)
VEC, PA, PB, O4, O5, O6 = (EXTRA + 0x100 * k for k in range(1, 7))


def wf(a, v):
    mu.mem_write(a, struct.pack("<f", v))


def rf(a):
    return struct.unpack("<f", bytes(mu.mem_read(a, 4)))[0]


def bits(x):
    return struct.unpack("<I", struct.pack("<f", x))[0]


def f32(x):
    return struct.unpack("<f", struct.pack("<f", x))[0]


def run(vec, a, b):
    for i, v in enumerate(vec):
        wf(VEC + 4 * i, v)
    wf(PA, a)
    wf(PB, b)
    for p in (O4, O5, O6):
        mu.mem_write(p, b"\xAA" * 16)
    emu.call(0x6F496D10, stack_args=(VEC, PA, PB, O4, O5, O6))
    return [rf(O4), rf(O4 + 4)], [rf(O5), rf(O5 + 4)], rf(O6)


def write_vectors(path, n=1500, seed=77):
    """Writes the Rust vector file (random move vectors, speeds around the 0.1 s refusal threshold, tiny vectors and
    whole numbers)."""
    rng = random.Random(seed)
    rows = []
    for i in range(n):
        mode = i % 5
        if mode == 0:
            dx, dy = rng.uniform(-300, 300), rng.uniform(-300, 300)
            a = rng.choice([0.0, rng.uniform(1, 60), rng.uniform(0.01, 1)])
        elif mode == 1:
            ln = rng.uniform(0.2, 80)
            a = ln / 0.1 * rng.uniform(0.98, 1.02)
            ang = rng.uniform(0, 6.283)
            dx, dy = ln * math.cos(ang), ln * math.sin(ang)
        elif mode == 2:
            dx, dy = rng.uniform(-0.3, 0.3), rng.uniform(-0.3, 0.3)
            a = rng.uniform(0.5, 5)
        elif mode == 3:
            dx, dy = rng.uniform(-20, 20), rng.uniform(-20, 20)
            a = rng.uniform(5, 40)
        else:
            dx, dy = rng.randrange(-40, 40) * 1.0, rng.randrange(-40, 40) * 1.0
            a = rng.choice([1.0, 10.0, 28.125, 32.0])
        dz, arc = rng.uniform(-5, 5), rng.choice([0.0, 0.25, 0.5, 1.0, 10.0])
        dx, dy, dz, a, arc = map(f32, (dx, dy, dz, a, arc))
        _o4, o5, o6 = run((dx, dy, dz), a, arc)
        rows.append((bits(dx), bits(dy), bits(a), bits(o6), bits(o5[0]), bits(o5[1])))
    out = ["// Generated by tools/emu/missile_cap_emu.py from the original Game.dll (0x6F496D10); do not edit.",
           "// (dx bits, dy bits, speed A bits, flight time T bits, velocity x bits, velocity y bits); cell units, "
           "A = cells per second.",
           "pub const ROWS: &[(u32, u32, u32, u32, u32, u32)] = &["]
    out += ["    (0x%08X, 0x%08X, 0x%08X, 0x%08X, 0x%08X, 0x%08X)," % r for r in rows]
    out.append("];")
    with open(path, "w", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")


if __name__ == "__main__":
    if len(sys.argv) > 2 and sys.argv[1] == "--rs":
        write_vectors(sys.argv[2])
        sys.exit(0)
    for vec, a, b in [((3.0, 4.0, 0.0), 1.0, 10.0), ((3.0, 4.0, 0.0), 0.0, 10.0), ((30.0, 40.0, 0.0), 1.0, 10.0),
                      ((30.0, 40.0, 2.0), 2.0, 10.0), ((0.0, 0.0, 0.0), 1.0, 10.0), ((1.0, 0.0, 0.0), 20.0, 10.0),
                      ((3.0, 4.0, 5.0), 900.0 / 32, 0.5)]:
        print(vec, a, b, "->", run(vec, a, b))
