#!/usr/bin/env python3
"""Differential vectors for the economy arithmetic of Game.dll 1.26a (docs/spec/economy-3.md).

Runs the ORIGINAL soft-float helpers in Unicorn (the user's own Game.dll is mapped at its image
base; nothing from it is written into the repository) and records input/output pairs for:

  refund  : f2i(mul(i2r(cost), rate))   the cancel refund of a train or research slot
            (0x6F062320 train branch: I2R of the cost, MUL by the refund-rate float, F2I)
  upkeep  : f2i(round(mul(tax, 100.0))) the upkeep tax rate in percent (0x6F40F620)

The constant 100.0 is read after the start-up initialisers have run (0x6FAAE574).
The gold tax defaults (0x6FAAE378 + 4*tier) are also read after the initialisers, and written
into the output so the Rust side can check its own defaults.

    GAME_DLL=/path/to/Game.dll PYTHONPATH=<dir with unicorn, pefile> \\
        python3 tools/emu/economy_vectors.py --seed 1 --n 3000 --rs crates/sim/tests/economy/vectors.rs

The generated Rust file holds plain numbers only (costs, float bit patterns, results).
"""
import argparse
import os
import random
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "jasscomp"))
import jcomp  # noqa: E402

I2R = 0x6F6EF350      # I2R: ECX = result pointer, EDX = the integer
MUL = 0x6F6EEE20      # MUL: ECX = result pointer, EDX = pointer to A, [esp+4] = pointer to B
ROUND = 0x6F6EF330    # ROUND: ECX = result pointer, EDX = pointer to operand
F2I = 0x6F6EEC20      # F2I: ECX = pointer to operand, EAX = integer
PERCENT_CONST = 0x6FAAE574
TAX_TABLE = 0x6FAAE378


def f32_bits(x):
    return struct.unpack("<I", struct.pack("<f", x))[0]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--n", type=int, default=3000)
    ap.add_argument("--rs", default=None, help="write a Rust test data file")
    args = ap.parse_args()

    H = jcomp.Harness()
    n_init, failed = jcomp.run_crt_init(H)
    print(f"initialisers run: {n_init}, failed: {len(failed)}")

    buf = H.alloc(64)
    res = buf          # result slot
    opa = buf + 8      # operand A
    opb = buf + 16     # operand B (stack argument for MUL)
    ptr_r = buf + 24   # pointer used by F2I / ROUND input

    def i2r(n):
        H.call(I2R, ecx=res, edx=n & 0xFFFFFFFF)
        return H.rd32(res)

    def mul(a_bits, b_bits):
        H.wr32(opa, a_bits)
        H.wr32(opb, b_bits)
        H.call(MUL, ecx=res, edx=opa, stack=(opb,))
        return H.rd32(res)

    def round_(a_bits):
        H.wr32(opa, a_bits)
        H.call(ROUND, ecx=res, edx=opa)
        return H.rd32(res)

    def f2i(a_bits):
        H.wr32(ptr_r, a_bits)
        return H.call(F2I, ecx=ptr_r) & 0xFFFFFFFF

    percent = H.rd32(PERCENT_CONST)
    tax_defaults = [H.rd32(TAX_TABLE + 4 * i) for i in range(10)]
    print("percent constant bits:", hex(percent), "tax defaults:", [hex(x) for x in tax_defaults])

    rng = random.Random(args.seed)
    # refund: integer costs and rates, plus the usual shipped-looking rates
    rates = [0.0, 0.25, 0.5, 0.75, 1.0, 0.1, 0.9, 0.2, 0.33, 0.66, 1.5, 2.0]
    rate_bits = [f32_bits(r) for r in rates]
    rate_bits += [rng.getrandbits(32) & 0x3F7FFFFF for _ in range(max(0, args.n // 6))]  # |x| < 1 floats
    costs = [0, 1, 2, 3, 5, 10, 75, 100, 125, 150, 175, 200, 300, 400, 500, 999, 1000, 1500,
             16777217, 16777219, 20000, 65535, 100000]
    costs += [rng.randint(0, 20000) for _ in range(args.n)]
    refund = []
    for c in costs:
        for rb in rng.sample(rate_bits, 4) + rate_bits[:3]:
            i = i2r(c)
            m = mul(i, rb)
            r = f2i(m)
            refund.append((c & 0xFFFFFFFF, rb, r))

    upkeep = []
    taxes = list(tax_defaults)
    taxes += [f32_bits(x) for x in (0.0, 0.3, 0.6, 0.05, 0.125, 0.5, 1.0, 0.7, 0.999)]
    taxes += [rng.getrandbits(32) & 0x3F7FFFFF for _ in range(args.n // 3)]
    for tb in taxes:
        m = mul(tb, percent)
        rr = round_(m)
        upkeep.append((tb, f2i(rr)))

    print(f"refund cases: {len(refund)}  upkeep cases: {len(upkeep)}")
    if args.rs:
        with open(args.rs, "w") as fh:
            fh.write("// Generated by tools/emu/economy_vectors.py from the original Game.dll (1.26a) in Unicorn.\n")
            fh.write("// Arithmetic only: (cost, rate bits, result) and (tax bits, percent). Do not hand-edit.\n\n")
            fh.write("#![allow(clippy::unreadable_literal)]\n\n")
            fh.write(f"pub const PERCENT_CONST_BITS: u32 = 0x{percent:08X};\n")
            fh.write("pub const GOLD_TAX_DEFAULT_BITS: [u32; 10] = [\n")
            for x in tax_defaults:
                fh.write(f"    0x{x:08X},\n")
            fh.write("];\n\n")
            fh.write("/// (cost, rate bits, f2i(mul(i2r(cost), rate)))\n")
            fh.write("pub const REFUND_VECTORS: &[(i32, u32, i32)] = &[\n")
            for c, rb, r in refund:
                fh.write(f"    ({c if c < 0x80000000 else c - 0x100000000}, 0x{rb:08X}, {r if r < 0x80000000 else r - 0x100000000}),\n")
            fh.write("];\n\n")
            fh.write("/// (tax bits, f2i(round(mul(tax, 100.0))))\n")
            fh.write("pub const UPKEEP_RATE_VECTORS: &[(u32, i32)] = &[\n")
            for tb, r in upkeep:
                fh.write(f"    (0x{tb:08X}, {r if r < 0x80000000 else r - 0x100000000}),\n")
            fh.write("];\n")
        print("wrote", args.rs)


if __name__ == "__main__":
    main()
