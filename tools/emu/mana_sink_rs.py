"""Writes `crates/sim/tests/mana_sink_vectors.rs` from the output of `mana_sink_emu.py`.

    python3 tools/emu/mana_sink_rs.py VECTORS.txt crates/sim/tests/mana_sink_vectors.rs

Input rows (from mana_sink_emu.py): `_ cur0 floor0 max0 hero_life delta mode cur1 floor1 max1 hero_life1 ret`.
"""
import sys


def main():
    src, dst = sys.argv[1], sys.argv[2]
    rows = []
    for line in open(src):
        f = line.split()
        if len(f) < 12:
            continue
        b0, b1, b2, delta, mode, a0, a1, a2 = f[1], f[2], f[3], f[5], f[6], f[7], f[8], f[9]
        rows.append("    ([0x%s, 0x%s, 0x%s], 0x%s, %s, [0x%s, 0x%s, 0x%s])," % (b0, b1, b2, delta, mode, a0, a1, a2))
    out = [
        "//! The hero mana sink against `Game.dll` 1.26a (`docs/spec/heroes.md`, section 10.5).",
        "//!",
        "//! The rows are the results of `tools/emu/mana_sink_emu.py 2000 13` (the real `0x6F278F50` run in Unicorn; valid",
        "//! mana states, zeros of either sign). Each row is `([current, floor, max] before, delta bits, mode,",
        "//! [current, floor, max] after)`. Generated by `tools/emu/mana_sink_rs.py`.",
        "",
        "use sim::heroes::{mana_sink, LifeCells};",
        "use softfloat::{Tables, F32};",
        "",
        "type Row = ([u32; 3], u32, u32, [u32; 3]);",
        "",
        "const VECTORS: &[Row] = &[",
    ]
    out += rows
    out += [
        "];",
        "",
        "fn tables() -> Option<Tables> {",
        "    let path = std::env::var(\"GAME_DLL\").ok()?;",
        "    let bytes = std::fs::read(path).ok()?;",
        "    Tables::from_game_dll(&bytes).ok()",
        "}",
        "",
        "#[test]",
        "fn mana_sink_matches_the_original_bit_for_bit() {",
        "    let Some(t) = tables() else {",
        "        return;",
        "    };",
        "    let mut bad = Vec::new();",
        "    for (i, &(before, delta, mode, after)) in VECTORS.iter().enumerate() {",
        "        let mut c = LifeCells {",
        "            life: F32::from_bits(before[0]),",
        "            floor: F32::from_bits(before[1]),",
        "            max: F32::from_bits(before[2]),",
        "        };",
        "        mana_sink(&mut c, F32::from_bits(delta), mode, Some(&t));",
        "        let got = [c.life.to_bits(), c.floor.to_bits(), c.max.to_bits()];",
        "        if got != after {",
        "            bad.push(format!(\"case {i}: got {got:08x?} want {after:08x?}\"));",
        "        }",
        "    }",
        "    assert!(bad.is_empty(), \"{} mismatches, first: {:?}\", bad.len(), bad.first());",
        "    let zero_results = VECTORS.iter().filter(|r| r.3[0] & 0x7fff_ffff == 0).count();",
        "    eprintln!(\"mana sink: {} cases bit-exact, {zero_results} with a zero current result\", VECTORS.len());",
        "}",
        "",
    ]
    open(dst, "w").write("\n".join(out))
    print("rows:", len(rows))


if __name__ == "__main__":
    main()
