#[test]
fn registry_matches_the_original_counters() {
    for (n, (ops, want)) in VECTORS.iter().enumerate() {
        let mut r = PrRegistry::new();
        let mut made: Vec<PrHandle> = Vec::new();
        let mut live1 = 0u32;
        for &(op, i) in ops.iter() {
            match op {
                0 => made.push(r.register()),
                1 => {
                    live1 += 1;
                    made.push(r.register_flagged());
                }
                _ => {
                    let h = made[i];
                    if h.slot & 0x8000_0000 != 0 {
                        live1 -= 1;
                    }
                    r.unregister(h);
                }
            }
        }
        assert_eq!(r.y(), want[0], "vector {n}: y");
        assert_eq!(r.x(), want[2], "vector {n}: x");
        assert_eq!(r.live() as u32, want[3], "vector {n}: live0");
        assert_eq!(live1, want[4], "vector {n}: live1");
    }
}
